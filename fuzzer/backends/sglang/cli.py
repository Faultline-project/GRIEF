"""
SGLang backend CLI — argparse registration and adapter construction.

Interface consumed by fuzzer/__main__.py:
    register_args(parser)       — add SGLang flags to a shared ArgumentParser
    build_adapter(args)         — return the right SglangAdapter if --sglang,
                                  else None
    resolve_seeds_dir(args, base_seeds_dir)
                                — return adapter-specific seeds subdir or None
    startup_lines(args, adapter)
                                — return list of [fuzzer] info lines to print

Mode priority (when --sglang is set): lora > spec > moe > base.
"""

from __future__ import annotations

import argparse
import os
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from ...core.adapter import TargetAdapter


def register_args(parser: argparse.ArgumentParser) -> None:
    """Add SGLang-specific flags to *parser*."""
    parser.add_argument(
        "--sglang", action="store_true",
        help="Target an SGLang server instead of vLLM. "
             "Server must be started with: python3 -m sglang.launch_server",
    )

    # LoRA multi-adapter isolation fuzzing
    parser.add_argument(
        "--sglang-lora", action="store_true",
        help="Enable SGLang LoRA adapter fuzzing mode (uses SglangLoRAAdapter). "
             "Requires the server to be started with --lora-paths.",
    )
    parser.add_argument(
        "--sglang-lora-weights-dir", default="/tmp/lora_weights", metavar="DIR",
        help="Directory containing lora_a/..lora_f/ subdirs generated by "
             "scripts/gen_lora_weights.py. All present subdirs are auto-discovered "
             "(default: /tmp/lora_weights)",
    )

    # Speculative decoding fuzzing
    parser.add_argument(
        "--sglang-spec", action="store_true",
        help="Enable SGLang speculative decoding fuzzing mode (uses SglangSpecAdapter). "
             "Server must be started with --speculative-algorithm.",
    )
    parser.add_argument(
        "--sglang-spec-algorithm", default="NGRAM", metavar="ALG",
        choices=["NGRAM", "EAGLE", "EAGLE3", "STANDALONE"],
        help="Speculative algorithm: 'NGRAM' (no extra weights, default), "
             "'EAGLE' or 'EAGLE3' (require --sglang-spec-draft-model-path), "
             "or 'STANDALONE'. Verified against SGLang 0.5.10.post1: NEXTN is an "
             "internal alias that maps to EAGLE and requires a draft model.",
    )
    parser.add_argument(
        "--sglang-spec-num-steps", type=int, default=5, metavar="N",
        help="Draft token count. Maps to --speculative-num-draft-tokens for NGRAM "
             "and --speculative-num-steps for EAGLE (default: 5).",
    )
    parser.add_argument(
        "--sglang-spec-draft-model-path", default="", metavar="PATH",
        help="Path to EAGLE draft model checkpoint. Required when "
             "--sglang-spec-algorithm EAGLE.",
    )
    parser.add_argument(
        "--sglang-spec-confirm-url", default="", metavar="URL",
        help="Base URL of a second SGLang server running WITHOUT speculative "
             "decoding. When set, suspicious traces are confirmed by replaying "
             "against both servers. If omitted, confirmation is disabled.",
    )

    # MoE batch-isolation fuzzing
    parser.add_argument(
        "--sglang-moe", action="store_true",
        help="Enable SGLang MoE batch-isolation fuzzing mode (uses SglangMoEAdapter). "
             "Oracle: output(R in batch) must equal output(R alone) at temperature=0.",
    )


def build_adapter(args: argparse.Namespace) -> "TargetAdapter | None":
    """Return the appropriate SGLang adapter, or None if --sglang was not passed.

    Priority: lora > spec > moe > base.
    """
    # --selection-policy is registered by the vLLM backend (both backends share
    # one parser) but applies to the Corpus regardless of backend, and this
    # build_adapter runs first, so publish it here too.  See
    # fuzzer/backends/vllm/cli.py::_apply_selection_policy.
    policy = getattr(args, "selection_policy", "") or ""
    if policy:
        os.environ["GRIEF_SELECTION_POLICY"] = policy
    # Likewise --fingerprint-version (registered by the vLLM backend, applies to
    # the Corpus regardless of backend).
    fp_version = getattr(args, "fingerprint_version", "") or ""
    if fp_version:
        os.environ["GRIEF_FINGERPRINT_VERSION"] = str(fp_version)

    if not getattr(args, "sglang", False):
        return None

    if getattr(args, "sglang_lora", False):
        from pathlib import Path
        from ...adapters.sglang_lora.adapter import SglangLoRAAdapter
        lora_dir = Path(args.sglang_lora_weights_dir)
        # Discover all adapter subdirs instead of hardcoding lora_a/lora_b.
        # gen_lora_weights.py creates lora_a..lora_f depending on --num-adapters,
        # so scanning the directory keeps client and server in sync automatically.
        _KNOWN_ORDER = ["lora_a", "lora_b", "lora_c", "lora_d", "lora_e", "lora_f"]
        adapters = {
            name: str(lora_dir / name)
            for name in _KNOWN_ORDER
            if (lora_dir / name).is_dir()
        }
        if len(adapters) < 2:
            raise RuntimeError(
                f"Expected at least 2 LoRA adapter dirs in {lora_dir}, "
                f"found: {list(adapters.keys())}. "
                f"Run scripts/gen_lora_weights.py first."
            )
        return SglangLoRAAdapter(adapters=adapters)

    if getattr(args, "sglang_spec", False):
        from ...adapters.sglang_spec.adapter import SglangSpecAdapter
        return SglangSpecAdapter(
            algorithm=args.sglang_spec_algorithm,
            num_steps=args.sglang_spec_num_steps,
            draft_model_path=args.sglang_spec_draft_model_path,
            confirm_url=args.sglang_spec_confirm_url,
        )

    if getattr(args, "sglang_moe", False):
        from ...adapters.sglang_moe.adapter import SglangMoEAdapter
        return SglangMoEAdapter()

    # Base SGLang surface: return the new-shape Adapter (Capabilities +
    # Strategy umbrella, Phase 3 of the adapter / strategy split).
    # It satisfies the TargetAdapter ABC, so the runner sees no change.
    from ...adapters.sglang.adapter import make_adapter
    return make_adapter()


def resolve_seeds_dir(args: argparse.Namespace, base_seeds_dir: str) -> str | None:
    """Return an adapter-specific seeds subdir path, or None."""
    from pathlib import Path
    if getattr(args, "sglang_lora", False):
        candidate = Path(base_seeds_dir) / "sglang_lora"
        if candidate.is_dir():
            return str(candidate)
    if getattr(args, "sglang_spec", False):
        candidate = Path(base_seeds_dir) / "sglang_spec"
        if candidate.is_dir():
            return str(candidate)
    if getattr(args, "sglang_moe", False):
        candidate = Path(base_seeds_dir) / "sglang_moe"
        if candidate.is_dir():
            return str(candidate)
    return None


def startup_lines(args: argparse.Namespace, adapter: "TargetAdapter") -> list[str]:
    """Return SGLang-specific [fuzzer] startup info lines."""
    kv_ep = getattr(args, "kv_events_endpoint", "")
    lines = ["[fuzzer] backend      : sglang"]
    if kv_ep:
        lines.append(f"[fuzzer] kv_events    : enabled  ({kv_ep})")
    else:
        lines.append(
            "[fuzzer] kv_events    : disabled "
            "(pass --kv-events-endpoint tcp://localhost:5557 to enable)"
        )

    if getattr(args, "sglang_lora", False) and adapter is not None:
        lines.append(
            f"[fuzzer] lora_mode    : enabled  ({list(adapter.adapters.keys())})"
        )
        lines.append(f"[fuzzer] lora_weights : {args.sglang_lora_weights_dir}")

    if getattr(args, "sglang_spec", False) and adapter is not None:
        lines.append(
            f"[fuzzer] spec_mode    : enabled  "
            f"(algorithm={args.sglang_spec_algorithm} "
            f"num_steps={args.sglang_spec_num_steps})"
        )
        if args.sglang_spec_algorithm == "EAGLE":
            lines.append(
                f"[fuzzer] spec_draft   : {args.sglang_spec_draft_model_path}"
            )
        if args.sglang_spec_confirm_url:
            lines.append(f"[fuzzer] spec_confirm : {args.sglang_spec_confirm_url}")
        else:
            lines.append(
                "[fuzzer] spec_confirm : disabled "
                "(pass --sglang-spec-confirm-url to enable)"
            )

    if getattr(args, "sglang_moe", False) and adapter is not None:
        lines.append("[fuzzer] moe_mode     : enabled  (batch-isolation oracle, temp=0)")

    return lines
