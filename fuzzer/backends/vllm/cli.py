"""
vLLM backend CLI — argparse registration and adapter construction.

Owns all vLLM-specific flags (--lora, --spec, --moe, --kv-events-endpoint)
and the logic for selecting which vLLM sub-adapter to instantiate.

Interface consumed by fuzzer/__main__.py:
    register_args(parser)       — add backend flags to a shared ArgumentParser
    build_adapter(args)         — return the right TargetAdapter (never None;
                                  vLLM is the default/fallback backend)
    resolve_seeds_dir(args, base_seeds_dir)
                                — return adapter-specific seeds subdir or None
    startup_lines(args, adapter)
                                — return list of [fuzzer] info lines to print
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from ...core.adapter import TargetAdapter


def _apply_selection_policy(args: argparse.Namespace) -> None:
    """Publish --selection-policy through the environment.

    Stopgap: `RunnerConfig` has no `selection_policy` field, and the `Corpus`
    is constructed inside `fuzzer/core/runner.py`, so there is no way to thread
    the flag through without editing the runner.  `Corpus.__init__` therefore
    reads `GRIEF_SELECTION_POLICY` when no explicit policy is passed
    (fuzzer/core/corpus.py).  Called from build_adapter(), which always runs
    before the Runner (and hence the Corpus) is constructed.

    Remove this once RunnerConfig gains the field.
    """
    policy = getattr(args, "selection_policy", "") or ""
    if policy:
        os.environ["GRIEF_SELECTION_POLICY"] = policy


def _apply_fingerprint_version(args: argparse.Namespace) -> None:
    """Publish --fingerprint-version through the environment.

    Same stopgap as _apply_selection_policy, for the same reason: the Corpus is
    constructed inside fuzzer/core/runner.py and RunnerConfig has no field for
    it.  `Corpus.__init__` reads `GRIEF_FINGERPRINT_VERSION` when no explicit
    version is passed, and `Runner._run_loop` reads the resolved value back off
    the Corpus to decide whether to build a v1 or a v2 fingerprint.

    Remove this once RunnerConfig gains the field.
    """
    version = getattr(args, "fingerprint_version", "") or ""
    if version:
        os.environ["GRIEF_FINGERPRINT_VERSION"] = str(version)


def register_args(parser: argparse.ArgumentParser) -> None:
    """Add all vLLM-specific flags to *parser*."""

    # Corpus selection policy (backend-agnostic; registered here because vLLM
    # is the default backend and both backends share one ArgumentParser).
    parser.add_argument(
        "--selection-policy", default="", choices=["", "v1", "v2"],
        metavar="POLICY",
        help="Corpus select() weighting policy. 'v1' (default) is the "
             "historical flat 0.01 floor; 'v2' enables the anti-collapse "
             "least-run-first floor (0.01 + 0.5/(1+run_count)) and the age "
             "decay on the score term. Exported as GRIEF_SELECTION_POLICY.",
    )
    parser.add_argument(
        "--fingerprint-version", default="", choices=["", "1", "2"],
        metavar="VERSION",
        help="Scheduler-fingerprint schema and novelty primitive. '1' "
             "(default) is the historical 8-dimension fingerprint with "
             "whole-tuple novelty. '2' adds three workload-derived dimensions "
             "(ttft_spread, concurrency_peak, error_class), counts fingerprint "
             "TRANSITIONS (prev -> cur) as a novelty signal beside the states, "
             "and re-weights each dimension by its measured entropy so "
             "invariant dimensions are down-weighted (never dropped) and "
             "re-probed. Exported as GRIEF_FINGERPRINT_VERSION.",
    )

    # KV cache event forensics
    parser.add_argument(
        "--kv-events-endpoint", default="", metavar="ENDPOINT",
        help="ZMQ endpoint for vLLM KV cache event stream "
             "(e.g. tcp://localhost:5557). Empty = disabled. "
             "Requires vLLM server started with "
             "--kv-events-config '{\"enable_kv_cache_events\": true}'",
    )

    # LoRA multi-adapter isolation fuzzing
    parser.add_argument(
        "--lora", action="store_true",
        help="Enable LoRA adapter fuzzing mode (uses VllmLoRAAdapter). "
             "Requires the server to be started with --enable-lora.",
    )
    parser.add_argument(
        "--lora-weights-dir", default="/tmp/lora_weights", metavar="DIR",
        help="Directory containing lora_a/ and lora_b/ subdirs generated by "
             "scripts/gen_lora_weights.py (default: /tmp/lora_weights)",
    )

    # Speculative decoding fuzzing
    parser.add_argument(
        "--spec", action="store_true",
        help="Enable speculative decoding fuzzing mode (uses VllmSpecAdapter). "
             "Server must be started with --speculative-config.",
    )
    parser.add_argument(
        "--spec-draft-model", default="[ngram]", metavar="MODEL",
        help="Draft model: '[ngram]' for n-gram (default, no weights needed), "
             "'[ngram_gpu]' for GPU-accelerated n-gram, "
             "'[eagle3]' for Eagle3 (requires --spec-eagle3-model), "
             "'[extract_hidden_states]' to target the extract_hidden_states "
             "spec method, or a HuggingFace model ID for a real draft model.",
    )
    parser.add_argument(
        "--spec-k", type=int, default=5, metavar="K",
        help="Default number of speculative tokens (default: 5). "
             "Ignored when --spec-draft-model=[extract_hidden_states] (k is "
             "pinned to 1 to match vLLM's extract_hidden_states contract).",
    )
    parser.add_argument(
        "--spec-eh-layers", type=int, default=35, metavar="N",
        help="Number of aux hidden-state layers to extract in "
             "extract_hidden_states mode (default: 35). More layers widen "
             "the race window.",
    )
    parser.add_argument(
        "--spec-eagle3-model", default="AngelSlim/Qwen3-8B_eagle3", metavar="MODEL",
        help="HuggingFace model ID for the Eagle3 draft model "
             "(default: AngelSlim/Qwen3-8B_eagle3). Only used when "
             "--spec-draft-model=[eagle3].",
    )
    parser.add_argument(
        "--spec-confirm-url", default="", metavar="URL",
        help="Base URL of a second vLLM server running WITHOUT speculative decoding. "
             "When set, suspicious traces are replayed against both servers and "
             "output divergence is reported as a confirmed bug. "
             "If omitted, no candidates are enqueued and confirmation is disabled.",
    )

    # MoE batch-isolation fuzzing
    parser.add_argument(
        "--moe", action="store_true",
        help="Enable MoE batch-isolation fuzzing mode (uses VllmMoEAdapter). "
             "Oracle: output(R in batch) must equal output(R alone) at temperature=0. "
             "Recommended model: Qwen/Qwen1.5-MoE-A2.7B-Chat",
    )
    parser.add_argument(
        "--embeds", action="store_true",
        help="Enable the prompt-embeddings surface adapter (VllmEmbedsAdapter): "
             "sampling parameters composed onto embedding requests. "
             "Server needs --enable-prompt-embeds; pair with --prompt-embeds-dim.",
    )


def build_adapter(args: argparse.Namespace) -> "TargetAdapter":
    """Return the appropriate vLLM adapter.

    Priority: lora > spec > moe > embeds > base.
    Always returns a non-None adapter — vLLM is the default backend.
    """
    _apply_selection_policy(args)
    _apply_fingerprint_version(args)

    if getattr(args, "sglang", False):
        # SGLang was selected; vLLM is not the active backend.
        return None  # type: ignore[return-value]

    if getattr(args, "lora", False):
        from ...adapters.vllm_lora.adapter import VllmLoRAAdapter
        lora_dir = Path(args.lora_weights_dir)
        return VllmLoRAAdapter(adapters={
            "lora_a": str(lora_dir / "lora_a"),
            "lora_b": str(lora_dir / "lora_b"),
        })

    if getattr(args, "spec", False):
        from ...adapters.vllm_spec.adapter import VllmSpecAdapter
        return VllmSpecAdapter(
            draft_model=args.spec_draft_model,
            default_k=args.spec_k,
            confirm_url=args.spec_confirm_url,
            eh_num_layers=getattr(args, "spec_eh_layers", 35),
            eagle3_model=getattr(args, "spec_eagle3_model", "AngelSlim/Qwen3-8B_eagle3"),
            eagle3_k=args.spec_k,
        )

    if getattr(args, "moe", False):
        from ...adapters.vllm_moe.adapter import VllmMoEAdapter
        return VllmMoEAdapter()

    if getattr(args, "embeds", False):
        from ...adapters.vllm_embeds.adapter import VllmEmbedsAdapter
        return VllmEmbedsAdapter()

    from ...adapters.vllm_base.adapter import VllmBaseAdapter
    return VllmBaseAdapter()


def resolve_seeds_dir(args: argparse.Namespace, base_seeds_dir: str) -> str | None:
    """Return an adapter-specific seeds subdir path, or None."""
    if getattr(args, "spec", False):
        candidate = Path(base_seeds_dir) / "vllm_spec"
        if candidate.is_dir():
            return str(candidate)
    if getattr(args, "moe", False):
        candidate = Path(base_seeds_dir) / "vllm_moe"
        if candidate.is_dir():
            return str(candidate)
    return None


def startup_lines(args: argparse.Namespace, adapter: "TargetAdapter") -> list[str]:
    """Return backend-specific [fuzzer] startup info lines."""
    lines = []

    if getattr(args, "lora", False) and adapter is not None:
        lines.append(f"[fuzzer] lora_mode    : enabled  ({list(adapter.adapters.keys())})")
        lines.append(f"[fuzzer] lora_weights : {args.lora_weights_dir}")

    if getattr(args, "spec", False) and adapter is not None:
        is_eh = args.spec_draft_model == "[extract_hidden_states]"
        is_eagle3 = args.spec_draft_model == "[eagle3]"
        # extract_hidden_states pins num_speculative_tokens=1 regardless of
        # --spec-k, so show the effective value rather than the flag value.
        k_display = 1 if is_eh else args.spec_k
        suffix = f" eh_layers={getattr(args, 'spec_eh_layers', 35)}" if is_eh else ""
        if is_eagle3:
            suffix = f" eagle3_model={getattr(args, 'spec_eagle3_model', '')}"
        lines.append(
            f"[fuzzer] spec_mode    : enabled  "
            f"(draft={args.spec_draft_model} k={k_display}{suffix})"
        )
        if args.spec_confirm_url:
            lines.append(f"[fuzzer] spec_confirm : {args.spec_confirm_url}")
        else:
            lines.append(
                "[fuzzer] spec_confirm : disabled "
                "(pass --spec-confirm-url to enable)"
            )

    if getattr(args, "moe", False) and adapter is not None:
        lines.append("[fuzzer] moe_mode     : enabled  (batch-isolation oracle, temp=0)")

    kv_ep = getattr(args, "kv_events_endpoint", "")
    if kv_ep:
        lines.append(f"[fuzzer] kv_events    : enabled  ({kv_ep})")
    else:
        lines.append(
            "[fuzzer] kv_events    : disabled "
            "(pass --kv-events-endpoint tcp://localhost:5557 to enable)"
        )

    return lines
